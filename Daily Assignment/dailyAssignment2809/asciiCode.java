package dailyAssignment2809;

public class asciiCode {
    public static void main(String[] args)
    {
        char a = 'A';
        char b = 'a';
        char c = '0';
        char d ='@';
        int asciiA= a;
        int asciiB= b;
        int asciiC=c;
        int asciiD= d;
        System.out.println("ASCII value of A = " +asciiA);
        System.out.println("ASCII value of a = " +asciiB);
        System.out.println("ASCII value of 0 = " +asciiC);
        System.out.println("ASCII value of @ = " +asciiD);
    }
}
